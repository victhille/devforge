import type { SfEntity, SfOperation } from '@shared/types'
import { plural } from './sfEntityWriter'

/**
 * The two API modes of the workshop:
 * - API Platform: #[ApiResource] and #[ApiProperty] written in the entities;
 * - JSON controllers: one plain controller per entity, written by DevForge.
 */

export const OPERATIONS: SfOperation[] = ['list', 'show', 'create', 'update', 'delete']

const PLATFORM_CLASS: Record<SfOperation, string> = { list: 'GetCollection', show: 'Get', create: 'Post', update: 'Patch', delete: 'Delete' }

/** URL of an entity's collection: /api/factures, /api/categories */
export const apiPath = (entity: string) => `/api/${plural(entity.charAt(0).toLowerCase() + entity.slice(1)).replace(/[A-Z]/g, c => `_${c.toLowerCase()}`)}`

const RESOURCE_LINE = /^[ \t]*#\[ApiResource(\(.*\))?\]\r?\n/m
const HIDDEN_LINE = /^[ \t]*#\[ApiProperty\(readable: false, writable: false\)\]\r?\n/gm
const PLATFORM_USES = ['ApiResource', 'ApiProperty', ...Object.values(PLATFORM_CLASS)].map(c => `use ApiPlatform\\Metadata\\${c};`)

/** True when the entity has an #[ApiResource] DevForge cannot rewrite (spread over several lines) */
export function handEditedResource(src: string): boolean {
  return src.includes('#[ApiResource') && !RESOURCE_LINE.test(src)
}

function addUses(src: string, lines: string[]): string {
  const missing = lines.filter(l => !src.includes(l))
  if (!missing.length) return src
  const lastUse = [...src.matchAll(/^use [^;]+;\r?$/gm)].pop()
  if (!lastUse) return src
  const at = lastUse.index! + lastUse[0].length
  return src.slice(0, at) + '\n' + missing.join('\n') + src.slice(at)
}

/** Removes the API Platform lines DevForge wrote (attributes and their use lines when unused) */
export function stripPlatform(src: string): string {
  let out = src.replace(RESOURCE_LINE, '').replace(HIDDEN_LINE, '')
  for (const line of PLATFORM_USES) {
    const cls = line.slice(line.lastIndexOf('\\') + 1, -1)
    const rest = out.replace(line, '')
    if (!new RegExp(`\\b${cls}\\b`).test(rest.replace(/^use .*$/gm, ''))) out = out.replace(new RegExp(`^${line.replace(/\\/g, '\\\\')}\\r?\\n`, 'm'), '')
  }
  return out
}

/** Entity file with #[ApiResource] for these operations and the hidden fields marked */
export function applyPlatform(src: string, operations: SfOperation[], hidden: string[]): string {
  let out = stripPlatform(src)
  if (!operations.length) return out
  const ops = OPERATIONS.filter(o => operations.includes(o)).map(o => `new ${PLATFORM_CLASS[o]}()`)
  out = out.replace(/^(#\[ORM\\Entity)/m, `#[ApiResource(operations: [${ops.join(', ')}])]\n$1`)
  for (const field of hidden) {
    out = out.replace(new RegExp(`^([ \\t]*)((?:private|protected|public)\\s+[^;=(]*\\$${field}\\b)`, 'm'), '$1#[ApiProperty(readable: false, writable: false)]\n$1$2')
  }
  const used = ['ApiResource', ...(hidden.length ? ['ApiProperty'] : []), ...OPERATIONS.filter(o => operations.includes(o)).map(o => PLATFORM_CLASS[o])]
  return addUses(out, used.map(c => `use ApiPlatform\\Metadata\\${c};`))
}

/**
 * API Platform answers JSON-LD only by default: plain application/json
 * (what the API Tester and most clients send) gets a 406. Adds both formats
 * to config/packages/api_platform.yaml when it sets none.
 */
export function withJsonFormat(yaml: string): string {
  if (/^\s+formats:/m.test(yaml)) return yaml
  return yaml.replace(/^api_platform:[ \t]*\r?\n/m, m => `${m}    formats:\n        jsonld: ['application/ld+json']\n        json: ['application/json']\n`)
}

export const GENERATED_MARK = '// Generated by DevForge'

export const controllerFile = (entity: string) => `src/Controller/Api/${entity}ApiController.php`

/**
 * A plain JSON controller: only the chosen operations and fields. Links to
 * one entity (ManyToOne) travel as ids: {"categorie": 3} in, {"categorie": {"id": 3}} out.
 */
export function jsonController(e: SfEntity, operations: SfOperation[], hidden: string[]): string {
  const name = e.name
  const v = name.charAt(0).toLowerCase() + name.slice(1)
  const fields = e.fields.filter(f => !hidden.includes(f.name))
  const links = e.relations.filter(r => r.kind === 'ManyToOne' && !hidden.includes(r.name))
  const required = [
    ...fields.filter(f => !f.nullable && f.type !== 'json').map(f => f.name),
    ...links.filter(r => !r.nullable).map(r => r.name)
  ]
  const route = apiPath(name)
  const prefix = `api_${name.replace(/[A-Z]/g, (c, i) => (i ? '_' : '') + c.toLowerCase())}_`
  const ctx = 'context: [AbstractNormalizer::ATTRIBUTES => self::OUTPUT]'
  const has = (o: SfOperation) => operations.includes(o)
  const writes = has('create') || has('update')
  const q = (xs: string[]) => xs.map(x => `'${x}'`).join(', ')

  // Shared by create and update: the body, then the links by id
  const readBody = `        $data = json_decode($request->getContent(), true);
        if (!is_array($data)) {
            return $this->json(['error' => 'The body must be a JSON object'], Response::HTTP_BAD_REQUEST);
        }`
  const setLinks = links.map(r => `        if (array_key_exists('${r.name}', $data)) {
            $${r.name} = $data['${r.name}'] === null ? null : $em->getRepository(${r.target}::class)->find($data['${r.name}']);
            if ($data['${r.name}'] !== null && $${r.name} === null) {
                return $this->json(['error' => 'Unknown ${r.name}', 'id' => $data['${r.name}']], Response::HTTP_UNPROCESSABLE_ENTITY);
            }
            $${v}->set${r.name.charAt(0).toUpperCase() + r.name.slice(1)}($${r.name});
        }`).join('\n')
  const validate = `        $errors = $validator->validate($${v});
        if (count($errors) > 0) {
            return $this->json($errors, Response::HTTP_UNPROCESSABLE_ENTITY);
        }`

  const actions: string[] = []
  if (has('list')) actions.push(`    #[Route('', name: 'list', methods: ['GET'])]
    public function list(${name}Repository $repository): JsonResponse
    {
        return $this->json($repository->findAll(), ${ctx});
    }`)
  if (has('show')) actions.push(`    #[Route('/{id}', name: 'show', methods: ['GET'], requirements: ['id' => '\\d+'])]
    public function show(${name} $${v}): JsonResponse
    {
        return $this->json($${v}, ${ctx});
    }`)
  if (has('create')) actions.push(`    #[Route('', name: 'create', methods: ['POST'])]
    public function create(Request $request, DenormalizerInterface $serializer, ValidatorInterface $validator, EntityManagerInterface $em): JsonResponse
    {
${readBody}
        $missing = array_values(array_diff(self::REQUIRED, array_keys($data)));
        if ($missing) {
            return $this->json(['error' => 'Missing fields', 'fields' => $missing], Response::HTTP_UNPROCESSABLE_ENTITY);
        }
        $${v} = $serializer->denormalize($data, ${name}::class, null, [AbstractNormalizer::ATTRIBUTES => self::INPUT]);
${setLinks ? setLinks + '\n' : ''}${validate}
        $em->persist($${v});
        $em->flush();

        return $this->json($${v}, Response::HTTP_CREATED, ${ctx});
    }`)
  if (has('update')) actions.push(`    #[Route('/{id}', name: 'update', methods: ['PATCH', 'PUT'], requirements: ['id' => '\\d+'])]
    public function update(${name} $${v}, Request $request, DenormalizerInterface $serializer, ValidatorInterface $validator, EntityManagerInterface $em): JsonResponse
    {
${readBody}
        $serializer->denormalize($data, ${name}::class, null, [
            AbstractNormalizer::OBJECT_TO_POPULATE => $${v},
            AbstractNormalizer::ATTRIBUTES => self::INPUT,
        ]);
${setLinks ? setLinks + '\n' : ''}${validate}
        $em->flush();

        return $this->json($${v}, ${ctx});
    }`)
  if (has('delete')) actions.push(`    #[Route('/{id}', name: 'delete', methods: ['DELETE'], requirements: ['id' => '\\d+'])]
    public function delete(${name} $${v}, EntityManagerInterface $em): JsonResponse
    {
        $em->remove($${v});
        $em->flush();

        return new JsonResponse(null, Response::HTTP_NO_CONTENT);
    }`)

  const targets = [...new Set(links.map(r => r.target).filter(t => t !== name))]
  const uses = [
    `use App\\Entity\\${name};`,
    ...(writes ? targets.map(t => `use App\\Entity\\${t};`) : []),
    ...(has('list') ? [`use App\\Repository\\${name}Repository;`] : []),
    ...(writes || has('delete') ? ['use Doctrine\\ORM\\EntityManagerInterface;'] : []),
    'use Symfony\\Bundle\\FrameworkBundle\\Controller\\AbstractController;',
    'use Symfony\\Component\\HttpFoundation\\JsonResponse;',
    ...(writes ? ['use Symfony\\Component\\HttpFoundation\\Request;'] : []),
    ...(writes || has('delete') ? ['use Symfony\\Component\\HttpFoundation\\Response;'] : []),
    'use Symfony\\Component\\Routing\\Attribute\\Route;',
    'use Symfony\\Component\\Serializer\\Normalizer\\AbstractNormalizer;',
    ...(writes ? ['use Symfony\\Component\\Serializer\\Normalizer\\DenormalizerInterface;', 'use Symfony\\Component\\Validator\\Validator\\ValidatorInterface;'] : [])
  ].sort((a, b) => a.localeCompare(b))
  const output = [`'id'`, ...fields.map(f => `'${f.name}'`), ...links.map(r => `'${r.name}' => ['id']`)].join(', ')
  return `<?php
${GENERATED_MARK}: rewritten when the API settings change in the Symfony workshop.

namespace App\\Controller\\Api;

${uses.join('\n')}

#[Route('${route}', name: '${prefix}')]
final class ${name}ApiController extends AbstractController
{
    /** Fields sent back; links as {"id": …} */
    private const OUTPUT = [${output}];

    /** Fields read from a request body (links are read by id, below) */
    private const INPUT = [${q(fields.map(f => f.name))}];

    /** Needed to create one */
    private const REQUIRED = [${q(required)}];

${actions.join('\n\n')}
}
`
}

/** Required fields hidden from the API: "create" cannot work without them */
export function hiddenRequired(e: SfEntity, hidden: string[]): string[] {
  return [
    ...e.fields.filter(f => !f.nullable && f.type !== 'json' && hidden.includes(f.name)).map(f => f.name),
    ...e.relations.filter(r => r.kind === 'ManyToOne' && !r.nullable && hidden.includes(r.name)).map(r => r.name)
  ]
}
