import type { SfEntity, SfField } from '@shared/types'

/** Faker call for a field, from its type and name: prices that fit, real emails, short names */
export function fakerFor(f: SfField): string | null {
  const n = f.name.toLowerCase()
  const u = f.unique ? 'unique()->' : ''
  const fk = `self::faker()->${u}`
  switch (f.type) {
    case 'decimal': {
      const scale = f.scale ?? 2
      const room = 10 ** Math.min((f.precision ?? 10) - scale, 6) - 1
      const max = /prix|price|montant|amount|total|cout|cost|tarif/.test(n) ? Math.min(room, 500) : room
      return `(string) ${fk}randomFloat(${scale}, 1, ${max})`
    }
    case 'float': return `${fk}randomFloat(2, 0, 1000)`
    case 'integer':
      if (/stock|quantit|qty|qte|nombre|count/.test(n)) return `${fk}numberBetween(0, 100)`
      if (/age/.test(n)) return `${fk}numberBetween(18, 90)`
      if (/ordre|order|position|rang/.test(n)) return `${fk}numberBetween(1, 50)`
      return `${fk}numberBetween(1, 1000)`
    case 'text': return `${fk}paragraph()`
    case 'string':
      if (/password|motdepasse/.test(n)) return null
      if (/mail/.test(n)) return `${fk}safeEmail()`
      if (/prenom|firstname/.test(n)) return `${fk}firstName()`
      if (/slug/.test(n)) return `${fk}slug()`
      if (/ville|city/.test(n)) return `${fk}city()`
      if (/phone|telephone|tel$/.test(n)) return `${fk}phoneNumber()`
      if (/url|site|link|lien/.test(n)) return `${fk}url()`
      if (/adresse|address/.test(n)) return `${fk}streetAddress()`
      if (/^(nom|name|titre|title|libelle|label|intitule)$/.test(n) || /nom$|name$/.test(n)) return `ucfirst(${fk}words(${f.unique ? 3 : 2}, true))`
      return `${fk}text(${Math.max(10, Math.min(f.length ?? 255, 60))})`
    default: return null
  }
}

/** Better defaults in a factory make:factory just wrote: only the lines of known fields change */
export function tuneFactory(src: string, e: SfEntity): string {
  let out = src
  for (const f of e.fields) {
    const call = fakerFor(f)
    if (!call) continue
    out = out.replace(new RegExp(`^([ \\t]*'${f.name}' => ).*,(\\r?)$`, 'm'), `$1${call},$2`)
  }
  return out
}

/**
 * Fake data with Foundry: one factory per entity (written by make:factory,
 * which fills every required field with Faker), and an AppFixtures that
 * creates the chosen counts, parents first, children linked to random parents.
 */

/** Entities in an order where every ManyToOne target comes first */
export function creationOrder(entities: SfEntity[], counts: Record<string, number>): SfEntity[] {
  const chosen = entities.filter(e => (counts[e.name] ?? 0) > 0)
  const done: SfEntity[] = []
  const visit = (e: SfEntity, path: Set<string>) => {
    if (done.includes(e) || path.has(e.name)) return
    path.add(e.name)
    for (const r of e.relations) {
      if (r.kind !== 'ManyToOne' && r.kind !== 'OneToOne') continue
      const parent = chosen.find(x => x.name === r.target)
      if (parent && parent !== e) visit(parent, path)
    }
    path.delete(e.name)
    if (!done.includes(e)) done.push(e)
  }
  for (const e of chosen) visit(e, new Set())
  return done
}

export function appFixtures(entities: SfEntity[], counts: Record<string, number>): string {
  const order = creationOrder(entities, counts)
  const lines = order.map(e => {
    const parents = e.relations.filter(r => r.kind === 'ManyToOne' && r.target !== e.name && (counts[r.target] ?? 0) > 0)
    const attrs = parents.map(r => `'${r.name}' => ${r.target}Factory::random()`)
    return attrs.length
      ? `        ${e.name}Factory::createMany(${counts[e.name]}, fn () => [${attrs.join(', ')}]);`
      : `        ${e.name}Factory::createMany(${counts[e.name]});`
  })
  return `<?php
// Generated by DevForge: rewritten from the "Fake data" panel of the Symfony workshop.

namespace App\\DataFixtures;

${order.map(e => `use App\\Factory\\${e.name}Factory;`).join('\n')}
use Doctrine\\Bundle\\FixturesBundle\\Fixture;
use Doctrine\\Persistence\\ObjectManager;

class AppFixtures extends Fixture
{
    public function load(ObjectManager $manager): void
    {
${lines.join('\n')}
    }
}
`
}
