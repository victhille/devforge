/**
 * Files the Next.js workshop writes: the shared Prisma client, the API route
 * handlers of a model, and the seed. Pure text; the service decides where.
 */

export const GENERATED_MARK = '// Generated by DevForge'
const lc = (s: string) => s.charAt(0).toLowerCase() + s.slice(1)

/** Where things import from, relative to the file being written */
export interface Imports {
  /** The generated client: "../app/generated/prisma/client" or "@prisma/client" */
  client: string
  /** lib/prisma, without extension */
  lib: string
}

/** lib/prisma.ts: one client for the app (kept across hot reloads), its driver adapter with Prisma 7 */
export function prismaClientFile(provider: string, prismaVersion: number, clientImport: string, ts: boolean): string {
  const adapter = prismaVersion >= 7 ? ADAPTER[provider] : undefined
  const make = adapter
    ? provider === 'postgresql'
      ? `new PrismaClient({ adapter: new ${adapter.cls}({ connectionString: process.env.DATABASE_URL }) })`
      : `new PrismaClient({ adapter: new ${adapter.cls}(${provider === 'sqlite' ? '{ url: process.env.DATABASE_URL ?? \'file:./dev.db\' }' : 'process.env.DATABASE_URL ?? \'\''}) })`
    : 'new PrismaClient()'
  return `${GENERATED_MARK}: one Prisma client for the whole app.
import { PrismaClient } from '${clientImport}'
${adapter ? `import { ${adapter.cls} } from '${adapter.pkg}'\n` : ''}
// Kept on globalThis: Next.js reloads modules in development, the connections stay
const globalForPrisma = globalThis${ts ? ' as unknown as { prisma?: PrismaClient }' : ''}

export const prisma = globalForPrisma.prisma ?? ${make}

if (process.env.NODE_ENV !== 'production') globalForPrisma.prisma = prisma
`
}

/** Fields of the API: the scalars not hidden, and the foreign keys of the links (categorieId) */
export function apiFields(e: SfEntity, hidden: string[]) {
  const scalars = e.fields.filter(f => !hidden.includes(f.name) && f.name !== 'createdAt')
  const fks = e.relations.filter(r => r.fk && !hidden.includes(r.name)).map(r => ({ name: r.fk!, required: !r.nullable }))
  return {
    input: [...scalars.map(f => f.name), ...fks.map(k => k.name)],
    required: [...scalars.filter(f => !f.nullable && f.type !== 'json').map(f => f.name), ...fks.filter(k => k.required).map(k => k.name)]
  }
}

const list = (xs: string[]) => `[${xs.map(x => `'${x}'`).join(', ')}]`

/** {app}/api/<models>/route.ts and [id]/route.ts, only the chosen operations */
export function routeFiles(e: SfEntity, ops: SfOperation[], hidden: string[], ts: boolean, imp: { collection: Imports; item: Imports }): { collection: string | null; item: string | null } {
  const model = lc(e.name)
  const { input, required } = apiFields(e, hidden)
  const omit = hidden.length ? `{ ${hidden.map(h => `${h}: true`).join(', ')} }` : '{}'
  const has = (o: SfOperation) => ops.includes(o)
  const typeImport = (i: Imports) => ts && (has('create') || has('update')) ? `import type { Prisma } from '${i.client}'\n` : ''
  const head = (i: Imports, rest: string) => `${GENERATED_MARK}: rewritten when the API settings change in the Next.js workshop.
import { NextResponse } from 'next/server'
${typeImport(i)}import { prisma } from '${i.lib}'
${rest}`
  const failCreate = `    return NextResponse.json({ error: String(err instanceof Error ? err.message : err).trim().split('\\n').pop() }, { status: 422 })`
  // A record that is not there (P2025) is a 404
  const fail = `    if (err && typeof err === 'object' && 'code' in err && err.code === 'P2025') return NOT_FOUND()\n${failCreate}`
  const readBody = `  const body = await request.json().catch(() => null)
  if (!body || typeof body !== 'object' || Array.isArray(body)) {
    return NextResponse.json({ error: 'The body must be a JSON object' }, { status: 400 })
  }
  const data = Object.fromEntries(INPUT.filter(k => k in body).map(k => [k, body[k]]))`
  const consts = (withRequired: boolean) => `
/** Fields accepted in a request body (links by id: categorieId) */
const INPUT = ${list(input)}${withRequired ? `\n/** Needed to create one */\nconst REQUIRED = ${list(required)}` : ''}
/** Fields never sent back */
const OMIT = ${omit}${ts ? ' as const' : ''}
`

  const collection = has('list') || has('create') ? head(imp.collection, consts(has('create')) + [
    has('list') ? `
export async function GET() {
  return NextResponse.json(await prisma.${model}.findMany({ omit: OMIT }))
}` : '',
    has('create') ? `
export async function POST(request${ts ? ': Request' : ''}) {
${readBody}
  const missing = REQUIRED.filter(k => !(k in body))
  if (missing.length) return NextResponse.json({ error: 'Missing fields', fields: missing }, { status: 422 })
  try {
    const created = await prisma.${model}.create({ data${ts ? `: data as Prisma.${e.name}UncheckedCreateInput` : ''}, omit: OMIT })
    return NextResponse.json(created, { status: 201 })
  } catch (err) {
${failCreate}
  }
}` : ''
  ].join('\n') + '\n') : null

  const params = ts ? '{ params }: { params: Promise<{ id: string }> }' : '{ params }'
  const idHelpers = `
const NOT_FOUND = () => NextResponse.json({ error: 'Not found' }, { status: 404 })

/** The id in the URL, or null when it is not a whole number */
async function idOf(params${ts ? ': Promise<{ id: string }>' : ''}) {
  const id = Number((await params).id)
  return Number.isInteger(id) && id > 0 ? id : null
}
`
  const item = has('show') || has('update') || has('delete') ? head(imp.item, consts(false) + idHelpers + [
    has('show') ? `
export async function GET(_request${ts ? ': Request' : ''}, ${params}) {
  const id = await idOf(params)
  const item = id === null ? null : await prisma.${model}.findUnique({ where: { id }, omit: OMIT })
  return item ? NextResponse.json(item) : NOT_FOUND()
}` : '',
    has('update') ? `
export async function PATCH(request${ts ? ': Request' : ''}, ${params}) {
  const id = await idOf(params)
  if (id === null) return NOT_FOUND()
${readBody}
  try {
    const updated = await prisma.${model}.update({ where: { id }, data${ts ? `: data as Prisma.${e.name}UncheckedUpdateInput` : ''}, omit: OMIT })
    return NextResponse.json(updated)
  } catch (err) {
${fail}
  }
}` : '',
    has('delete') ? `
export async function DELETE(_request${ts ? ': Request' : ''}, ${params}) {
  const id = await idOf(params)
  if (id === null) return NOT_FOUND()
  try {
    await prisma.${model}.delete({ where: { id } })
    return new NextResponse(null, { status: 204 })
  } catch {
    return NOT_FOUND()
  }
}` : ''
  ].join('\n') + '\n') : null

  return { collection, item }
}

