import type { DbColumnInfo, DbTableRef, DbType } from '../types'
import { quoteColumn, quoteIdent } from './sqlQuote'

/**
 * v3.5.1: the SQL that creates, changes or drops a table or a column, per
 * engine. Shown before it runs; each statement runs on its own (MySQL takes
 * one at a time).
 */

export interface ColumnDef {
  name: string
  /** INT, VARCHAR(255), NUMERIC(10, 2), TEXT[]… */
  type: string
  nullable: boolean
  /** As typed: a number, a keyword (CURRENT_TIMESTAMP, now()…) or text, quoted for you */
  default: string
  primary: boolean
  autoIncrement: boolean
}

export const EMPTY_COLUMN: ColumnDef = { name: '', type: '', nullable: true, default: '', primary: false, autoIncrement: false }

/** The usual types, offered in the type field (any other valid one can be typed) */
export const COLUMN_TYPES: Record<DbType, string[]> = {
  postgres: ['integer', 'bigint', 'smallint', 'serial', 'numeric(10, 2)', 'real', 'double precision', 'boolean', 'varchar(255)', 'text', 'uuid', 'date', 'timestamp', 'timestamptz', 'time', 'json', 'jsonb', 'bytea'],
  mysql: ['INT', 'BIGINT', 'SMALLINT', 'TINYINT(1)', 'DECIMAL(10, 2)', 'FLOAT', 'DOUBLE', 'BOOLEAN', 'VARCHAR(255)', 'CHAR(36)', 'TEXT', 'LONGTEXT', 'DATE', 'DATETIME', 'TIMESTAMP', 'TIME', 'JSON', 'BLOB'],
  sqlite: ['INTEGER', 'REAL', 'NUMERIC', 'TEXT', 'BLOB', 'BOOLEAN', 'DATE', 'DATETIME']
}

/** A type name, sizes and an array suffix: nothing else gets into the SQL */
const TYPE_RE = /^[A-Za-z][A-Za-z0-9_]*( [A-Za-z][A-Za-z0-9_]*)*(\(\s*\d+\s*(,\s*\d+\s*)?\))?( (unsigned|zerofill))*(\[\])?$/i

export const validType = (type: string) => TYPE_RE.test(type.trim())

const KEYWORDS = /^(null|true|false|current_timestamp|current_date|current_time|localtimestamp|now\(\)|gen_random_uuid\(\)|uuid\(\))$/i

/** A default as SQL: numbers and known keywords as they are, the rest as a quoted string */
export function defaultSql(value: string): string {
  const v = value.trim()
  if (/^-?\d+(\.\d+)?$/.test(v) || KEYWORDS.test(v)) return v
  // Already SQL: a quoted string (with a cast), a function call
  if (/^'(?:[^']|'')*'(::[a-z ]+)?$/i.test(v) || /^[a-z_][a-z0-9_.]*\(.*\)$/i.test(v)) return v
  return `'${v.replace(/'/g, "''")}'`
}

const isIntType = (type: string) => /^(tiny|small|medium|big)?int(eger)?\b|^serial|^bigserial/i.test(type.trim())

/** What is wrong with a column, or null */
export function columnProblem(db: DbType, c: ColumnDef): 'name' | 'type' | 'autoIncrement' | null {
  if (!c.name.trim()) return 'name'
  if (!validType(c.type)) return 'type'
  if (c.autoIncrement && (!isIntType(c.type) || !c.primary)) return 'autoIncrement'
  if (c.autoIncrement && db === 'sqlite' && !/^integer$/i.test(c.type.trim())) return 'autoIncrement'
  return null
}

function columnSql(db: DbType, c: ColumnDef, inlinePrimary: boolean): string {
  const parts = [quoteColumn(db, c.name.trim()), c.type.trim()]
  if (db === 'sqlite' && inlinePrimary) parts.push('PRIMARY KEY')
  if (c.autoIncrement) parts.push(db === 'mysql' ? 'AUTO_INCREMENT' : db === 'postgres' ? 'GENERATED BY DEFAULT AS IDENTITY' : 'AUTOINCREMENT')
  if (!c.nullable && !(db === 'sqlite' && inlinePrimary)) parts.push('NOT NULL')
  if (c.default.trim() && !c.autoIncrement) parts.push(`DEFAULT ${defaultSql(c.default)}`)
  return parts.join(' ')
}

export function createTableSql(db: DbType, table: DbTableRef, columns: ColumnDef[]): string[] {
  const keys = columns.filter(c => c.primary)
  // SQLite's AUTOINCREMENT needs the key on the column itself
  const inline = db === 'sqlite' && keys.length === 1 && keys[0].autoIncrement
  const lines = columns.map(c => '  ' + columnSql(db, c, inline && c === keys[0]))
  if (keys.length && !inline) lines.push(`  PRIMARY KEY (${keys.map(c => quoteColumn(db, c.name.trim())).join(', ')})`)
  return [`CREATE TABLE ${quoteIdent(db, table)} (\n${lines.join(',\n')}\n)`]
}

export function renameTableSql(db: DbType, table: DbTableRef, name: string): string[] {
  // The new name stays in the table's schema
  const to = quoteIdent(db, { name: name.trim(), schema: '' })
  return db === 'mysql' ? [`RENAME TABLE ${quoteIdent(db, table)} TO ${to}`] : [`ALTER TABLE ${quoteIdent(db, table)} RENAME TO ${to}`]
}

export const dropTableSql = (db: DbType, table: DbTableRef): string[] => [`DROP TABLE ${quoteIdent(db, table)}`]

export function addColumnSql(db: DbType, table: DbTableRef, c: ColumnDef): string[] {
  return [`ALTER TABLE ${quoteIdent(db, table)} ADD COLUMN ${columnSql(db, { ...c, primary: false, autoIncrement: false }, false)}`]
}

export const dropColumnSql = (db: DbType, table: DbTableRef, name: string): string[] =>
  [`ALTER TABLE ${quoteIdent(db, table)} DROP COLUMN ${quoteColumn(db, name)}`]

/** A column as the Structure tab shows it, for its edit form */
export function columnDefOf(c: DbColumnInfo): ColumnDef {
  const auto = /auto_increment|identity|autoincrement/i.test(c.extra) || /^nextval\(/i.test(c.default ?? '')
  return {
    name: c.name, type: c.type, nullable: c.nullable, primary: c.key === 'PRI', autoIncrement: auto,
    default: auto || c.default === null || /^null$/i.test(c.default) ? '' : c.default
  }
}

/**
 * The statements that turn `before` into `after`. SQLite can only rename a
 * column: any other change returns 'unsupported'.
 */
export function alterColumnSql(db: DbType, table: DbTableRef, before: DbColumnInfo, after: ColumnDef): string[] | 'unsupported' {
  const t = quoteIdent(db, table)
  const was = columnDefOf(before)
  const name = after.name.trim()
  const renamed = name !== before.name
  const retyped = after.type.trim() !== was.type
  const nulls = after.nullable !== was.nullable
  const defaulted = after.default.trim() !== was.default.trim()

  if (db === 'sqlite') {
    if (retyped || nulls || defaulted) return 'unsupported'
    return renamed ? [`ALTER TABLE ${t} RENAME COLUMN ${quoteColumn(db, before.name)} TO ${quoteColumn(db, name)}`] : []
  }

  if (db === 'mysql') {
    if (!renamed && !retyped && !nulls && !defaulted) return []
    // CHANGE restates the whole column: keep its auto-increment and comment
    const parts = [quoteColumn(db, name), after.type.trim(), after.nullable ? 'NULL' : 'NOT NULL']
    if (after.default.trim() && !was.autoIncrement) parts.push(`DEFAULT ${defaultSql(after.default)}`)
    if (was.autoIncrement) parts.push('AUTO_INCREMENT')
    if (before.comment) parts.push(`COMMENT '${before.comment.replace(/'/g, "''")}'`)
    return [`ALTER TABLE ${t} CHANGE COLUMN ${quoteColumn(db, before.name)} ${parts.join(' ')}`]
  }

  const col = quoteColumn(db, name)
  const out: string[] = []
  if (renamed) out.push(`ALTER TABLE ${t} RENAME COLUMN ${quoteColumn(db, before.name)} TO ${col}`)
  if (retyped) out.push(`ALTER TABLE ${t} ALTER COLUMN ${col} TYPE ${after.type.trim()} USING ${col}::${after.type.trim()}`)
  if (nulls) out.push(`ALTER TABLE ${t} ALTER COLUMN ${col} ${after.nullable ? 'DROP' : 'SET'} NOT NULL`)
  if (defaulted) out.push(after.default.trim() ? `ALTER TABLE ${t} ALTER COLUMN ${col} SET DEFAULT ${defaultSql(after.default)}` : `ALTER TABLE ${t} ALTER COLUMN ${col} DROP DEFAULT`)
  return out
}
