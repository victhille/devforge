import { expect, test } from '@playwright/test'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'fs'
import { join } from 'path'
import { goTo, launch, type Launched } from './launch'
import { settledAxeIssues } from './axe'
import { shop } from '../shopMcd'

/** v3.9 lot 3: the MLD worked out from the MCD, the MPD made and touched up, the SQL written in the project */
let run: Launched
test.afterEach(async () => {
  expect(run.errors, 'uncaught page errors').toEqual([])
  await run.close()
})

test('MCD → MLD → MPD → SQL, hand changes kept when the MCD changes', async () => {
  let project = ''
  run = await launch({
    seed: dir => {
      project = join(dir, 'shop')
      mkdirSync(join(project, 'conception'), { recursive: true })
      // The project's database runs on MySQL: the MPD starts on it
      writeFileSync(join(project, '.env'), 'DATABASE_URL=mysql://app:secret@127.0.0.1:3306/shop\n')
      writeFileSync(join(project, 'conception', 'boutique.mcd.json'), JSON.stringify({ v: 1, kind: 'mcd', name: 'Boutique', updatedAt: '2026-10-01T10:00:00.000Z', mcd: shop() }))
      writeFileSync(join(dir, 'projects.json'), JSON.stringify([{ id: 's', name: 'shop', path: project, framework: 'other', packageManager: 'npm', favorite: false, createdAt: '', lastOpenedAt: null }]))
    }
  })
  const { page, app } = run
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1440, 900))
  await goTo(page, '/modeling')
  const chain = page.getByRole('region', { name: 'La chaîne du projet' })
  await expect(chain).toContainText('7 relation(s)')
  await expect(chain).toContainText('Pas encore de MPD')

  // The MLD: relations, keys, the rules applied
  await chain.locator('[data-step="mld"]').click()
  await expect(page.locator('[data-relation="COMMANDE"]')).toHaveText('COMMANDE ( id_commande, passee_le, statut, #id_client )')
  await expect(page.locator('[data-relation="CONTENIR"]')).toContainText('#id_commande, #id_produit, quantite')
  const rules = page.getByRole('region', { name: 'Règles appliquées' })
  await expect(rules).toContainText('CONTENIR : plusieurs des deux côtés, elle devient une relation')
  await expect(rules).toContainText('PASSER (0,n — 1,1) : la clé de CLIENT descend dans COMMANDE comme #id_client.')
  expect(await settledAxeIssues(page)).toEqual([])

  // The MPD, made on the project's engine
  await page.getByRole('button', { name: 'Générer le MPD' }).click()
  const canvas = page.getByTestId('mpd-canvas')
  await expect(canvas.locator('[data-table="commande_produit"]')).toBeVisible()
  await expect(page.getByLabel('Moteur')).toHaveValue('mysql')
  const mpdFile = join(project, 'conception', 'boutique.mpd.json')
  expect(existsSync(mpdFile)).toBe(true)
  await expect(page.getByRole('button', { name: 'Vérifier' })).toBeVisible()

  // Touched up by hand: a longer libelle, an index
  await canvas.locator('[data-table="produit"]').click({ position: { x: 20, y: 10 } })
  const panel = page.getByRole('complementary', { name: 'Table' })
  await expect(panel.getByLabel('Nom de la table')).toHaveValue('produit')
  await panel.getByLabel('Longueur de libelle').fill('150')
  await panel.getByRole('button', { name: 'Index', exact: true }).click()
  await expect(panel.getByLabel('Nom de l’index')).toHaveValue('idx_produit_libelle')
  await expect.poll(() => {
    const t = JSON.parse(readFileSync(mpdFile, 'utf-8')).mpd.tables.find((x: { name: string }) => x.name === 'produit')
    return [t.columns.find((c: { name: string }) => c.name === 'libelle').length, t.indexes.length]
  }, { timeout: 10_000 }).toEqual([150, 1])
  expect(await settledAxeIssues(page)).toEqual([])

  // The SQL, for MySQL, then written in the project
  await page.getByRole('navigation', { name: 'Étapes du modèle' }).getByRole('button', { name: 'SQL' }).click()
  const sql = page.getByTestId('mpd-sql')
  await expect(sql).toContainText('id INT AUTO_INCREMENT PRIMARY KEY')
  await expect(sql).toContainText('libelle VARCHAR(150)')
  await expect(sql).toContainText('PRIMARY KEY (commande_id, produit_id)')
  await expect(sql).toContainText('CREATE INDEX idx_produit_libelle ON produit (libelle);')
  await page.getByRole('button', { name: 'Écrire boutique.sql' }).click()
  const sqlFile = join(project, 'conception', 'boutique.sql')
  await expect.poll(() => existsSync(sqlFile)).toBe(true)
  expect(readFileSync(sqlFile, 'utf-8')).toContain('CREATE TABLE commande_produit')
  // Another engine rewrites the types
  await page.getByLabel('Moteur').selectOption('postgres')
  await expect(sql).toContainText('id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
  await expect(page.getByText('Le fichier écrit est plus ancien que le MPD.')).toBeVisible()
  expect(await settledAxeIssues(page)).toEqual([])

  // The MCD changes: the MPD says so, and its update keeps the hand change
  await page.getByRole('navigation', { name: 'Étapes du modèle' }).getByRole('button', { name: 'MCD' }).click()
  await page.getByRole('complementary', { name: 'Palette' }).getByRole('button', { name: 'PRODUIT' }).click()
  const element = page.getByRole('complementary', { name: 'Élément choisi' })
  await element.getByRole('button', { name: 'Attribut', exact: true }).click()
  await element.getByLabel('Nom de l’attribut').last().fill('poids')
  await page.getByRole('navigation', { name: 'Étapes du modèle' }).getByRole('button', { name: 'MPD' }).click()
  await expect(page.getByText('Le MCD a changé depuis ce MPD.')).toBeVisible()
  await page.getByRole('button', { name: 'Mettre à jour', exact: true }).click()
  await expect(page.getByText('Le MCD a changé depuis ce MPD.')).toBeHidden()
  await expect(canvas.locator('[data-table="produit"]')).toContainText('poids')
  await expect(canvas.locator('[data-table="produit"]')).toContainText('VARCHAR(150)')

  // The chain, back on the page: the MPD up to date, its SQL to write again
  await page.getByRole('button', { name: 'Modélisation' }).click()
  await expect(chain.locator('[data-step="mpd"]')).toContainText('7 table(s) · PostgreSQL')
  await expect(chain.locator('[data-step="mpd"]')).toContainText('● À jour')
  await expect(chain.locator('[data-step="sql"]')).toContainText('▲ À mettre à jour')
  await expect(page.getByRole('region', { name: 'Modèles du projet' }).getByRole('listitem')).toHaveCount(2)
})
