import { expect, test } from '@playwright/test'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'fs'
import { join } from 'path'
import { goTo, launch, type Launched } from './launch'
import { settledAxeIssues as settledAxe } from './axe'

/** v2.3 lot 4: Auth.js from the Next.js workshop (packages faked, files really written) */
let run: Launched
test.afterEach(async () => {
  expect(run.errors, 'uncaught page errors').toEqual([])
  await run.close()
})

const SCHEMA = 'generator client {\n  provider = "prisma-client"\n  output   = "../app/generated/prisma"\n}\n\ndatasource db {\n  provider = "postgresql"\n}\n\nmodel Note {\n  id    Int    @id @default(autoincrement())\n  texte String\n}\n'

test('providers, the files written, the keys saved and never shown again', async () => {
  let dir = ''
  run = await launch({
    env: { DEVFORGE_TEST_NEXTJS: '{userData}/nextjs.json' },
    seed: data => {
      dir = join(data, 'site')
      for (const d of ['prisma', 'app', 'lib']) mkdirSync(join(dir, d), { recursive: true })
      for (const pkg of ['next-auth', '@auth/prisma-adapter', 'bcryptjs', '@prisma/client']) {
        mkdirSync(join(dir, 'node_modules', ...pkg.split('/')), { recursive: true })
        writeFileSync(join(dir, 'node_modules', ...pkg.split('/'), 'package.json'), '{}')
      }
      writeFileSync(join(dir, 'package.json'), JSON.stringify({ dependencies: { next: '16.0.0', 'next-auth': '5.0.0-beta.32' }, devDependencies: { prisma: '6.0.0' } }))
      writeFileSync(join(dir, 'tsconfig.json'), '{}')
      writeFileSync(join(dir, 'prisma', 'schema.prisma'), SCHEMA)
      writeFileSync(join(dir, 'lib', 'prisma.ts'), '// Generated by DevForge: one Prisma client for the whole app.\nexport const prisma = {}\n')
      writeFileSync(join(dir, 'auth.ts'), "import NextAuth from 'next-auth'\n\nexport const { handlers, auth, signIn, signOut } = NextAuth({ providers: [] })\n")
      writeFileSync(join(data, 'projects.json'), JSON.stringify([
        { id: 'nx', name: 'site', path: dir, framework: 'nextjs', packageManager: 'npm', favorite: false, createdAt: '2026-01-01T00:00:00.000Z', lastOpenedAt: null }
      ]))
      writeFileSync(join(data, 'nextjs.json'), JSON.stringify({ database: { reachable: true, error: null }, migrations: [] }))
    }
  })
  const { page } = run
  await goTo(page, '/project/nx?tab=nextjs')
  await page.getByRole('navigation', { name: 'Atelier Next.js' }).getByRole('button', { name: /Utilisateurs et connexion/ }).click()
  await expect(page.getByRole('checkbox', { name: /E-mail et mot de passe/ })).toBeChecked()
  await page.getByRole('checkbox', { name: /GitHub/ }).check({ force: true })
  await expect(page.getByText('+ app/inscription/page.tsx')).toBeVisible()
  await expect(page.getByText('~ prisma/schema.prisma (User, Account, Session, VerificationToken)')).toBeVisible()
  expect(await settledAxe(page)).toEqual([])

  await page.getByRole('button', { name: 'Écrire la configuration' }).click()
  await expect(page.getByText(/fichier\(s\) écrit\(s\)/)).toBeVisible()
  expect(readFileSync(join(dir, 'prisma', 'schema.prisma'), 'utf-8')).toContain('model VerificationToken {')
  expect(readFileSync(join(dir, 'auth.ts'), 'utf-8')).toContain("import GitHub from 'next-auth/providers/github'")
  expect(existsSync(join(dir, 'app', 'connexion', 'page.tsx'))).toBe(true)
  expect(existsSync(join(dir, 'app', 'api', 'moi', 'route.ts'))).toBe(true)
  expect(readFileSync(join(dir, '.env.local'), 'utf-8')).toMatch(/^AUTH_SECRET="[^"]{20,}"$/m)

  // The keys go to .env.local and the fields are emptied: never shown again
  const keys = page.getByRole('group', { name: 'Clés GitHub' })
  await expect(keys).toContainText('manquantes')
  await keys.getByRole('textbox', { name: 'AUTH_GITHUB_ID' }).fill('id-de-test')
  await keys.getByLabel('AUTH_GITHUB_SECRET').fill('secret-de-test')
  await keys.getByRole('button', { name: 'Enregistrer' }).click()
  await expect(page.getByText('2 clé(s) enregistrée(s) dans .env.local.')).toBeVisible()
  await expect(keys).toContainText('renseignées')
  await expect(keys.getByLabel('AUTH_GITHUB_SECRET')).toHaveValue('')
  expect(readFileSync(join(dir, '.env.local'), 'utf-8')).toContain('AUTH_GITHUB_SECRET="secret-de-test"')
  expect(await settledAxe(page)).toEqual([])
})
